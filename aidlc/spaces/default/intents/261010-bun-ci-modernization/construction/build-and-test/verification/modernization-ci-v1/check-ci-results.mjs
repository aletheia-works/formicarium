import assert from 'node:assert/strict';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const source = '7fc23afedef9a2296cb24026c0f19998a6933da7';
const tarball = '742e1c368bd913d786c6baa3c5d1e1e82cbc252e38e0cc78429f9f1098bc30ca';
const directory = resolve(root, '.artifacts/modernization-current-v1/ci-run-38087834465', `modernization-${source}-38087834465-1`);
const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const { validateChecks, validateCoverage } = await import(pathToFileURL(resolve(root, 'scripts/ci/verification.js')));
const { FILES, REQUIRED_U1_REALMS } = await import(pathToFileURL(resolve(root, 'scripts/terrarium/coverage.js')));
const acceptance = await readJson(resolve(directory, 'ci-results/acceptance.json'));
const coverage = await readJson(resolve(directory, 'ci-coverage-fixed24/report.json'));
const inventory = await readJson(resolve(directory, 'ci-coverage-fixed24/inventory.json'));
const u1 = await readJson(resolve(directory, 'u1-coverage-v1000001/coverage-report.json'));
assert.equal(acceptance.passed, true);
assert.deepEqual(acceptance.context, {repository:'aletheia-works/formicarium',commit:source,event:'workflow_dispatch',ref:'refs/heads/codex/verify/bun-ci-modernization-v1'});
assert.equal(acceptance.manifestSha256, hash(await readFile(resolve(root, '.artifacts/modernization-current-v1/inputs-v5/manifest.json'))));
assert.deepEqual(acceptance.coverage, coverage);
validateChecks(acceptance.checks);
validateCoverage(coverage, {files:FILES,tarballSha256:tarball,u1Realms:REQUIRED_U1_REALMS});
assert.equal(u1.candidateSha256, tarball);
assert.equal(u1.passed, true);
assert.ok(u1.lines.pct >= 80);
assert.equal(u1.lines.skipped, 0);
assert.equal(inventory.tarballSha256, tarball);
assert.equal(inventory.candidate.sha256, coverage.candidateSha256);
assert.equal(inventory.sourceIdentity, coverage.sourceIdentity);
assert.deepEqual(coverage.files.map(row=>row.path), [...FILES]);
assert.equal(coverage.lines.total, coverage.files.reduce((sum,row)=>sum+row.lines.total,0));
assert.equal(coverage.lines.covered, coverage.files.reduce((sum,row)=>sum+row.lines.covered,0));
assert.ok(100*coverage.lines.covered/coverage.lines.total>=80);
assert.ok(coverage.freshReceipts.every(row=>row.status==='passed'));
const commands=[];
for(const name of await readdir(resolve(directory,'ci-results'))){
  if(!name.endsWith('.json')||name==='acceptance.json')continue;
  const row=await readJson(resolve(directory,'ci-results',name));
  assert.equal(row.exitCode,0); assert.equal(row.timedOut,false); assert.equal(row.skipped,0);
  for(const stream of ['stdout','stderr'])assert.equal(hash(await readFile(resolve(directory,'ci-results',`${row.id}.${stream}.txt`))),row[`${stream}Sha256`]);
  commands.push({id:row.id,passed:row.passed,skipped:row.skipped,exitCode:row.exitCode,started:row.started,finished:row.finished});
}
const summary={passed:true,runId:38087834465,source,tarball,checks:acceptance.checks.map(({id,passed,skipped,exitCode})=>({id,passed,skipped,exitCode})),commandsVerified:commands.length,coverage:coverage.lines,fixedInventoryFiles:FILES.length,freshReceipts:coverage.freshReceipts.length,u1Coverage:u1.lines,u1Realms:u1.realmNames.length,manifestSha256:acceptance.manifestSha256,commands};
await writeFile(new URL('ci-observations.json',import.meta.url),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary));
